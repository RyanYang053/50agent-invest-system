"""Checkpointed, bounded research workflow inspired by durable graphs/TradingAgents.
No broker tools. Stage inputs immutable; callbacks must be idempotent and trusted
operator implementations, not arbitrary code generated by a model.
"""
from __future__ import annotations
import json,sqlite3
from contextlib import closing
from .ledger import digest,canonical,iso

STAGES=('evidence','discovery','fundamental','valuation','bull','bear','verification','portfolio_risk','decision','postmortem_plan')

class Committee:
    def __init__(self,path):
        self.path=str(path)
        with closing(sqlite3.connect(self.path)) as c:
            c.executescript('''CREATE TABLE IF NOT EXISTS committee_runs(id TEXT PRIMARY KEY,request TEXT NOT NULL);
            CREATE TABLE IF NOT EXISTS committee_stages(run_id TEXT NOT NULL,stage TEXT NOT NULL,output TEXT NOT NULL,sha TEXT NOT NULL, PRIMARY KEY(run_id,stage));''')
    def start(self, *, security_id, at, policy_hash, strategy_version,input_hash=None):
        if not security_id or not policy_hash or not strategy_version:raise ValueError('missing run provenance')
        request={'security_id':security_id,'decision_at':iso(at).isoformat(),'policy_hash':policy_hash,'strategy_version':strategy_version,'input_hash':input_hash,'can_trade':False}
        rid=digest(request)
        with closing(sqlite3.connect(self.path)) as c,c:c.execute('INSERT OR IGNORE INTO committee_runs VALUES(?,?)',(rid,canonical(request)))
        return rid
    def state(self,rid):
        with closing(sqlite3.connect(self.path)) as c:
            r=c.execute('SELECT request FROM committee_runs WHERE id=?',(rid,)).fetchone()
            if r is None:raise KeyError('unknown run')
            request=json.loads(r[0]);rows=c.execute('SELECT stage,output,sha FROM committee_stages WHERE run_id=?',(rid,)).fetchall()
        if digest(request)!=rid:raise ValueError('request integrity failure')
        out={}
        for stage,raw,sha in rows:
            v=json.loads(raw)
            if digest(v)!=sha:raise ValueError('stage integrity failure')
            out[stage]=v
        if set(out)!=set(STAGES[:len(out)]):raise ValueError('stage sequence integrity failure')
        return request,out
    def append(self,rid,stage,result):
        if not isinstance(result,dict) or result.get('can_trade') is not False:raise ValueError('unsafe stage result')
        raw=json.dumps(result,allow_nan=False,sort_keys=True,ensure_ascii=False)
        if len(raw.encode())>250_000:raise ValueError('stage payload too large')
        with closing(sqlite3.connect(self.path,timeout=10)) as c,c:
            c.execute('BEGIN IMMEDIATE')
            request,prior=self.state(rid)
            if stage in prior:
                if digest(prior[stage])!=digest(result):raise ValueError('stage output immutable')
                return 'DUPLICATE'
            if len(prior)==len(STAGES) or stage!=STAGES[len(prior)]:raise ValueError('out of order stage')
            if stage in ('bull','bear') and not result.get('researcher_id'):raise ValueError('missing researcher identity')
            if stage=='bear' and result['researcher_id']==prior['bull']['researcher_id']:raise ValueError('countercase not independent')
            if stage=='verification':
                if result.get('status') not in ('OK','VERIFIED'):raise ValueError('verification not passed')
                if result.get('reviewer_id') in (None,'',prior['bull']['researcher_id'],prior['bear']['researcher_id']):raise ValueError('independent reviewer required')
                if result.get('reviewed_hashes')!={k:digest(prior[k]) for k in ('fundamental','valuation','bull','bear')}:raise ValueError('review not bound to artifacts')
            if stage=='decision' and (result.get('decision')!='WAIT' or result.get('position_size') is not None):raise ValueError('research committee must remain WAIT')
            c.execute('INSERT INTO committee_stages VALUES(?,?,?,?)',(rid,stage,raw,digest(result)))
        return 'RECORDED'
    def advance(self,rid,handlers):
        request,prior=self.state(rid)
        if len(prior)==len(STAGES):return {'status':'COMPLETE_RESEARCH_ONLY','decision':prior['decision'],'can_trade':False}
        stage=STAGES[len(prior)]
        if stage not in handlers:return {'status':'BLOCKED_MISSING_HANDLER','stage':stage,'can_trade':False}
        result=handlers[stage](digest({'run':rid,'stage':stage}),request,prior)
        if not isinstance(result,dict) or result.get('status') in ('BLOCK','FAILED','INSUFFICIENT_DATA','NO_EVIDENCE'):
            return {'status':'BLOCKED_STAGE','stage':stage,'can_trade':False}
        self.append(rid,stage,result)
        return {'status':'CHECKPOINTED','stage':stage,'can_trade':False}
