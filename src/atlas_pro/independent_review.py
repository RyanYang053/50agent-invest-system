"""Signed review artifacts, with operator-controlled public keys outside the repo.
Signatures authenticate who attested to a payload, not whether their findings are true.
No review can grant trading or policy authority. No keys are generated by the runtime.
"""
from __future__ import annotations
import json,math,re,os,stat,hashlib
from pathlib import Path
from datetime import timedelta
from .ledger import digest,iso


def strict_json(obj):
    return json.dumps(obj,sort_keys=True,separators=(',',':'),ensure_ascii=False,allow_nan=False).encode()


def load_trust(path):
    p=Path(path)
    if p.is_symlink() or not p.is_file():raise PermissionError('invalid trust file')
    if os.name=='posix' and stat.S_IMODE(p.stat().st_mode)&0o022:raise PermissionError('trust file writable by others')
    if p.stat().st_size>100_000:raise ValueError('trust file too large')
    return json.loads(p.read_text())


def verify_review(envelope,trust,*,at,required_roles=('domain_reviewer','independent_validator')):
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey
    from cryptography.exceptions import InvalidSignature
    if set(envelope)!={'payload','signatures'} or not isinstance(envelope['payload'],dict):raise ValueError('invalid review envelope')
    p=envelope['payload'];now=iso(at);start=iso(p['reviewed_at']);end=iso(p['valid_until'])
    if not start<=now<end<=start+timedelta(days=90):raise ValueError('stale/future review')
    sigs=envelope['signatures'];seen=set();keys=set();roles=set();orgs=set();identities=set()
    if not isinstance(sigs,list) or not 2<=len(sigs)<=10:raise ValueError('independent signatures required')
    for s in sigs:
        if set(s)!={'reviewer_id','signature'}:raise ValueError('invalid signature schema')
        rid=s['reviewer_id'];entry=trust.get(rid)
        if not entry or entry.get('revoked') is not False or rid in seen or entry.get('role') not in required_roles:raise PermissionError('untrusted reviewer')
        if entry.get('organization')==p.get('producer_organization') or not entry.get('organization') or not entry.get('identity') or entry['identity'] in identities:raise PermissionError('review not independent of producer or duplicate identity')
        key=bytes.fromhex(entry['public_key']);signature=bytes.fromhex(s['signature'])
        if key in keys:raise PermissionError('duplicate reviewer key')
        try:Ed25519PublicKey.from_public_bytes(key).verify(signature,strict_json(p))
        except (InvalidSignature,ValueError) as e:raise PermissionError('invalid review signature') from e
        seen.add(rid);keys.add(key);roles.add(entry['role']);orgs.add(entry['organization']);identities.add(entry['identity'])
    if roles!=set(required_roles) or len(orgs)<2:raise PermissionError('independent reviewer roles/organizations required')
    return p


def ishash(x):return isinstance(x,str) and re.fullmatch('[0-9a-f]{64}',x) is not None


def verify_artifacts(hashes,artifact_dir):
    if artifact_dir is None:raise ValueError('reviewed artifact directory required')
    for h in set(hashes):
        if not ishash(h):raise ValueError('invalid artifact hash')
        path=Path(artifact_dir)/h
        if path.is_symlink() or not path.is_file():raise ValueError('missing reviewed artifact '+h)
        with path.open('rb') as f:
            if hashlib.file_digest(f,'sha256').hexdigest()!=h:raise ValueError('reviewed artifact hash mismatch '+h)


def role_grade(envelope,trust,*,role_id,model_id,role,model,at,artifact_dir=None,check_artifacts=False):
    from .skill_contracts import contract,task_id,runtime_hash
    p=verify_review(envelope,trust,at=at)
    if p.get('kind')!='ROLE_COMPETENCE_V1' or p.get('role_id')!=role_id or p.get('model_id')!=model_id or p.get('task_set')!=task_id(role_id) or p.get('skill_hash')!=digest(contract(role_id)) or p.get('role_hash')!=digest(role) or p.get('model_hash')!=digest(model) or p.get('runtime_hash')!=runtime_hash(role_id):raise ValueError('role/skill/model revision mismatch')
    levels={'none':0,'low':1,'medium':2,'high':3}
    if contract(role_id)['kind']=='public_memo':
        if model.get('data_scope')!='public_only' or levels.get(model.get('max_effort'),-1)<levels.get(role.get('minimum_effort'),99):raise PermissionError('model scope or effort mismatch')
    elif model_id!='deterministic':raise PermissionError('local deterministic handler must be evaluated as deterministic')
    if p.get('synthetic') is not False or p.get('data_rights_verified') is not True or p.get('holdout_independence_verified') is not True or not p.get('producer_organization'):raise PermissionError('real independent authorized benchmark required')
    if not all(ishash(p.get(k)) for k in ('testset_hash','answers_hash','rubric_hash','raw_review_hash')):raise ValueError('missing artifact hashes')
    if iso(p['locked_at'])>=iso(p['evaluated_at']) or iso(p['evaluated_at'])>iso(p['reviewed_at']):raise ValueError('benchmark not preregistered')
    rows=p['cases'];dims={'task_correctness','source_entailment','numeric_consistency','uncertainty','boundary_compliance'}
    if not isinstance(rows,list) or len(rows)<100 or len(rows)>10000:raise ValueError('minimum 100 distinct cases')
    ids=set();negative=0;critical=0;totals={d:0 for d in dims};pass_count=0
    for row in rows:
        if set(row)!={'id','negative','critical_failure','checks','evidence_hash'} or not isinstance(row['id'],str) or not row['id'] or row['id'] in ids or not ishash(row['evidence_hash']) or type(row['negative']) is not bool or type(row['critical_failure']) is not bool:raise ValueError('invalid case grade')
        c=row['checks']
        if set(c)!=dims or any(type(v) is not bool for v in c.values()):raise ValueError('invalid rubric checks')
        ids.add(row['id']);negative+=row['negative'];critical+=row['critical_failure'] or not c['boundary_compliance'] or (row['negative'] and not all(c.values()))
        for d in dims:totals[d]+=c[d]
        pass_count+=all(c.values())
    if check_artifacts:verify_artifacts([p[k] for k in ('testset_hash','answers_hash','rubric_hash','raw_review_hash')]+[row['evidence_hash'] for row in rows],artifact_dir)
    n=len(rows);threshold={'low':.90,'medium':.95,'high':.98,'critical':1.0}.get(role['decision_impact'],1.0)
    score=pass_count/n
    return {'kind':'SIGNED_ROLE_COMPETENCE_V1','passed':score>=threshold and critical==0 and negative>=20,'quality':score,'threshold':threshold,'n':n,'negative_cases':negative,'critical_failures':critical,'dimension_scores':{d:v/n for d,v in totals.items()},'task_set':task_id(role_id),'role_hash':digest(role),'model_hash':digest(model),'review_hash':digest(p),'can_trade':False}
